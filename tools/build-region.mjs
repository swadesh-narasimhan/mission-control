// Builds www/region.js: land polygons for the India - Southeast Asia SKY map.
// Source: Natural Earth 1:50m land (public domain), clipped to the region and simplified.
// The app rasterises these rings onto its dot grid at runtime.
// Usage: node tools/build-region.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'www', 'region.js');
const BOX = { w: 35, e: 145, s: -30, n: 50 }; // generous: the visible window depends on screen shape
const TOL = 0.04; // degrees (~4 km) for simplification

const gj = await (await fetch('https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson')).json();

function clipRing(ring) { // Sutherland-Hodgman against the box
  const edges = [
    (p) => p[0] >= BOX.w, (p) => p[0] <= BOX.e, (p) => p[1] >= BOX.s, (p) => p[1] <= BOX.n
  ];
  const cut = [
    (a, b) => { const t = (BOX.w - a[0]) / (b[0] - a[0]); return [BOX.w, a[1] + t * (b[1] - a[1])]; },
    (a, b) => { const t = (BOX.e - a[0]) / (b[0] - a[0]); return [BOX.e, a[1] + t * (b[1] - a[1])]; },
    (a, b) => { const t = (BOX.s - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BOX.s]; },
    (a, b) => { const t = (BOX.n - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BOX.n]; }
  ];
  let out = ring;
  for (let e = 0; e < 4; e++) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      const ci = edges[e](cur), pi = edges[e](prev);
      if (ci) { if (!pi) out.push(cut[e](prev, cur)); out.push(cur); }
      else if (pi) out.push(cut[e](prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let idx = -1, max = 0;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; st.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const rings = [];
for (const f of gj.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const outer = poly[0];
    let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
    for (const [x, y] of outer) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    if (x1 < BOX.w || x0 > BOX.e || y1 < BOX.s || y0 > BOX.n) continue;
    const c = simplify(clipRing(outer.slice(0, -1)), TOL);
    if (c.length < 3) continue;
    rings.push(c.flatMap(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]));
  }
}
const js = '/* Generated by tools/build-region.mjs from Natural Earth 1:50m land (public domain). */\n' +
  'window.MC_REGION = ' + JSON.stringify({ box: BOX, rings }) + ';\n';
writeFileSync(OUT, js);
console.log(`wrote ${OUT}: ${rings.length} rings, ${rings.reduce((a, r) => a + r.length / 2, 0)} points, ${(js.length / 1024).toFixed(1)} KB`);
